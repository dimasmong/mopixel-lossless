let locale = 'en';
try { if (localStorage.getItem('mopixel-language') === 'id') locale = 'id'; } catch {}
const originalText = new WeakMap();
const ids = Object.keys(STATIC_EN);

export function language() { return locale; }
export function t(key, values = {}) {
  const template = MESSAGES[locale][key] ?? MESSAGES.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ''));
}

export function applyTranslations(root = document.body) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (['SCRIPT', 'STYLE'].includes(node.parentElement?.tagName)) continue;
    if (!originalText.has(node)) originalText.set(node, node.nodeValue);
    const original = originalText.get(node);
    const clean = original.trim();
    // Keep whitespace around inline elements intact.
    if (!clean || !(clean in STATIC_EN)) continue;
    const translated = locale === 'en' ? STATIC_EN[clean] : (STATIC_ID[clean] ?? clean);
    const left = original.match(/^\s*/)[0];
    const right = original.match(/\s*$/)[0];
    node.nodeValue = left + translated + right;
  }
  document.documentElement.lang = locale;
  document.title = 'MoPixel — Lossless Image Optimizer';
  document.querySelector('meta[name="description"]')?.setAttribute('content', locale === 'en'
    ? 'MoPixel — free, privacy-first lossless image optimization right in your browser.'
    : 'MoPixel — optimasi gambar lossless gratis dan privat langsung di browser.');
  document.querySelector('.brand')?.setAttribute('aria-label', t('home'));
  document.querySelector('.workspace')?.setAttribute('aria-label', t('workspace'));
  document.querySelector('#dropZone')?.setAttribute('aria-label', t('uploadArea'));
  const langSelect = document.querySelector('#languageSelect');
  if (langSelect) { langSelect.value = locale; langSelect.setAttribute('aria-label', t('language')); langSelect.title = t('language'); }
}

export function setLanguage(next) {
  if (next !== 'en' && next !== 'id') return;
  locale = next;
  try { localStorage.setItem('mopixel-language', next); } catch {}
  applyTranslations();
}
